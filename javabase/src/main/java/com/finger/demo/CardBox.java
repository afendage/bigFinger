package com.finger.demo;


public class CardBox {

	private String name;
	
	private String status;
	
	private String dateStr;
	
	private String code;

	private String boxType;
	
	private String cardColor;
	
	private String shufferType;
	
	private String shufferName;
	
	private String userName;
	
	private String usedNum;
	
	private String tableNo;
	
	private String bootNo;
	
	private String dealer;

	private String area;

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}

	public String getStatus() {
		return status;
	}

	public void setStatus(String status) {
		this.status = status;
	}

	public String getDateStr() {
		return dateStr;
	}

	public void setDateStr(String dateStr) {
		this.dateStr = dateStr;
	}

	public String getCode() {
		return code;
	}

	public void setCode(String code) {
		this.code = code;
	}

	public String getBoxType() {
		return boxType;
	}

	public void setBoxType(String boxType) {
		this.boxType = boxType;
	}

	public String getCardColor() {
		return cardColor;
	}

	public void setCardColor(String cardColor) {
		this.cardColor = cardColor;
	}

	public String getShufferType() {
		return shufferType;
	}

	public void setShufferType(String shufferType) {
		this.shufferType = shufferType;
	}

	public String getShufferName() {
		return shufferName;
	}

	public void setShufferName(String shufferName) {
		this.shufferName = shufferName;
	}

	public String getUserName() {
		return userName;
	}

	public void setUserName(String userName) {
		this.userName = userName;
	}

	public String getUsedNum() {
		return usedNum;
	}

	public void setUsedNum(String usedNum) {
		this.usedNum = usedNum;
	}

	public String getTableNo() {
		return tableNo;
	}

	public void setTableNo(String tableNo) {
		this.tableNo = tableNo;
	}

	public String getBootNo() {
		return bootNo;
	}

	public void setBootNo(String bootNo) {
		this.bootNo = bootNo;
	}

	public String getDealer() {
		return dealer;
	}

	public void setDealer(String dealer) {
		this.dealer = dealer;
	}

	public String getArea() {
		return area;
	}

	public void setArea(String area) {
		this.area = area;
	}
}
